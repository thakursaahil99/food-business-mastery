"use client";

import { motion } from "motion/react";
import { useState } from "react";
import { AlertTriangle, CheckCircle2, Clock, Download, Pencil, RotateCcw, Trash2 } from "lucide-react";
import { deletePayment, savePayment, type PaymentInput } from "@/lib/actions/admin-crud";
import { AddButton, ConfirmDelete, DateInput, FormError, FormFooter, Modal, NumberInput, Select, istDateToIso, isoToIstDate, useAdminAction } from "./crud";
import { toast } from "sonner";
import type { PaymentRow } from "@/lib/types";
import { fmtDate, formatINR } from "@/lib/utils";
import { Avatar, Empty, Kpi, Page, PageHeader, PaymentPill, Tabs, fadeUp } from "./ui";

type F = "all" | PaymentRow["status"];
const lakh = (n: number) => (n >= 100000 ? `₹${(n / 100000).toFixed(2)}L` : formatINR(n));

type StudentOption = { name: string; batchName: string };

export function AdminPaymentsView({ payments, students, canDelete }: { payments: PaymentRow[]; students: StudentOption[]; canDelete: boolean }) {
  const [f, setF] = useState<F>("all");
  const [editing, setEditing] = useState<PaymentRow | "new" | null>(null);
  const [removing, setRemoving] = useState<PaymentRow | null>(null);
  const del = useAdminAction();
  const sum = (s: PaymentRow["status"]) => payments.filter((p) => p.status === s).reduce((a, p) => a + p.amount, 0);
  const shown = payments.filter((p) => f === "all" || p.status === f);
  const count = (s: F) => (s === "all" ? payments.length : payments.filter((p) => p.status === s).length);

  return (
    <Page>
      <PageHeader title="Payments" sub="Razorpay payments, verified by webhook. Amounts exclude 18% GST." actions={<AddButton onClick={() => setEditing("new")}>Record payment</AddButton>} />
      <div className="grid grid-cols-2 gap-4 lg:grid-cols-4">
        <Kpi dark icon={CheckCircle2} label="Collected" value={sum("captured")} format={lakh} />
        <Kpi icon={Clock} label="Pending" value={sum("pending")} format={lakh} />
        <Kpi icon={AlertTriangle} label="Failed" value={sum("failed")} format={lakh} />
        <Kpi icon={RotateCcw} label="Refunded" value={sum("refunded")} format={lakh} />
      </div>
      <motion.div variants={fadeUp}>
        <Tabs
          id="pay"
          value={f}
          onChange={setF}
          options={(["all", "captured", "pending", "failed", "refunded"] as F[]).map((v) => ({ value: v, label: v === "all" ? "All" : v === "captured" ? "Paid" : v[0]!.toUpperCase() + v.slice(1), count: count(v) }))}
        />
      </motion.div>
      <motion.div variants={fadeUp} className="overflow-x-auto rounded-[24px] border border-line bg-surface">
        {shown.length === 0 ? (
          <div className="p-5">
            <Empty>No payments here.</Empty>
          </div>
        ) : (
          <table className="w-full min-w-[760px] text-sm">
            <thead>
              <tr className="border-b border-line text-left text-xs uppercase tracking-wider text-fg-muted">
                <th className="px-5 py-3 font-medium">Student</th>
                <th className="px-3 py-3 font-medium">Date</th>
                <th className="px-3 py-3 font-medium">Method</th>
                <th className="px-3 py-3 text-right font-medium">Amount</th>
                <th className="px-3 py-3 font-medium">Status</th>
                <th className="px-3 py-3 font-medium">Invoice</th>
                <th className="px-5 py-3 text-right font-medium">Actions</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-line">
              {shown.map((p, i) => (
                <motion.tr key={p.id} initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: i * 0.03 }} className="hover:bg-surface-2/60">
                  <td className="px-5 py-3">
                    <div className="flex items-center gap-3">
                      <Avatar name={p.studentName} />
                      <div className="min-w-0">
                        <div className="truncate font-medium text-fg">{p.studentName}</div>
                        <div className="truncate font-mono text-[11px] text-fg-muted">{p.razorpayPaymentId ?? "—"}</div>
                      </div>
                    </div>
                  </td>
                  <td className="px-3 py-3 text-fg-muted">{fmtDate(p.paidAt)}</td>
                  <td className="px-3 py-3 text-fg-muted">{p.method}</td>
                  <td className="px-3 py-3 text-right">
                    <div className="font-semibold tabular-nums text-fg">{formatINR(p.amount)}</div>
                    <div className="text-[11px] tabular-nums text-fg-muted">+ {formatINR(p.gst)} GST</div>
                  </td>
                  <td className="px-3 py-3">
                    <PaymentPill status={p.status} />
                  </td>
                  <td className="px-3 py-3">
                    {p.invoiceNo ? (
                      <button onClick={() => toast("GST invoice PDFs are generated by the Laravel API")} className="inline-flex items-center gap-1.5 text-xs font-medium text-fg hover:text-bean-600">
                        <Download className="size-3.5" /> {p.invoiceNo}
                      </button>
                    ) : (
                      <span className="text-xs text-fg-muted">—</span>
                    )}
                  </td>
                  <td className="px-5 py-3 text-right">
                    <span className="inline-flex gap-1">
                      <button onClick={() => setEditing(p)} className="grid size-9 place-items-center rounded-lg text-fg-muted hover:bg-surface-2 hover:text-fg" aria-label={"Edit payment by " + p.studentName} title="Edit">
                        <Pencil className="size-4" />
                      </button>
                      {canDelete && (
                        <button onClick={() => setRemoving(p)} className="grid size-9 place-items-center rounded-lg text-fg-muted hover:bg-bean-50 hover:text-bean-700" aria-label={"Delete payment by " + p.studentName} title="Delete">
                          <Trash2 className="size-4" />
                        </button>
                      )}
                    </span>
                  </td>
                </motion.tr>
              ))}
            </tbody>
          </table>
        )}
      </motion.div>

      <PaymentForm key={editing === "new" ? "new" : (editing?.id ?? "none")} payment={editing} students={students} onClose={() => setEditing(null)} />
      <ConfirmDelete
        open={!!removing}
        onClose={() => setRemoving(null)}
        pending={del.pending}
        error={del.error}
        title="Delete this payment record?"
        body={
          <>
            The {removing ? formatINR(removing.amount) : ""} payment by <b>{removing?.studentName}</b> will be removed from reports. Use this only for entries made by mistake. For money returned to a student, edit the payment and set it to Refunded instead.
          </>
        }
        onConfirm={() => {
          const p = removing!;
          del.run(() => deletePayment(p.id), "Payment deleted", () => setRemoving(null));
        }}
      />
    </Page>
  );
}

function PaymentForm({ payment, students, onClose }: { payment: PaymentRow | "new" | null; students: StudentOption[]; onClose: () => void }) {
  const editing = payment && payment !== "new" ? payment : null;
  const people = editing && !students.some((s) => s.name === editing.studentName) ? [{ name: editing.studentName, batchName: editing.batchName }, ...students] : students;
  const [f, setF] = useState(() => ({
    studentName: editing?.studentName ?? people[0]?.name ?? "",
    batchName: editing?.batchName ?? people[0]?.batchName ?? "",
    amount: editing?.amount ?? 50000,
    method: editing?.method ?? ("UPI" as PaymentRow["method"]),
    status: editing?.status ?? ("captured" as PaymentRow["status"]),
    date: editing ? isoToIstDate(editing.paidAt) : isoToIstDate(new Date().toISOString()),
  }));
  const act = useAdminAction();
  const save = () => {
    const input: PaymentInput = { studentName: f.studentName, batchName: f.batchName, amount: f.amount, method: f.method, status: f.status, paidAt: istDateToIso(f.date, "12:00") };
    act.run(() => savePayment(editing?.id ?? null, input), editing ? "Payment updated" : "Payment recorded", onClose);
  };
  return (
    <Modal
      open={!!payment}
      onClose={onClose}
      title={editing ? "Edit payment" : "Record a payment"}
      sub={editing ? undefined : "For cash, cheque or bank transfers. Online payments arrive from Razorpay on their own."}
      footer={<FormFooter onCancel={onClose} onSave={save} pending={act.pending} saveLabel={editing ? "Save changes" : "Record payment"} />}
    >
      <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
        <Select
          label="Student"
          value={f.studentName}
          onChange={(v) => setF((x) => ({ ...x, studentName: v, batchName: people.find((s) => s.name === v)?.batchName ?? x.batchName }))}
          options={people.map((s) => ({ value: s.name, label: s.name + " · " + s.batchName.split(" · ")[0] }))}
          className="sm:col-span-2"
        />
        <NumberInput label="Amount (₹)" hint="before GST" value={f.amount} onChange={(v) => setF((x) => ({ ...x, amount: v }))} min={1} step={500} />
        <DateInput label="Date" value={f.date} onChange={(v) => setF((x) => ({ ...x, date: v }))} />
        <Select label="Method" value={f.method} onChange={(v) => setF((x) => ({ ...x, method: v }))} options={(["UPI", "Card", "Netbanking", "EMI"] as const).map((m) => ({ value: m, label: m }))} />
        <Select
          label="Status"
          value={f.status}
          onChange={(v) => setF((x) => ({ ...x, status: v }))}
          options={[
            { value: "captured" as const, label: "Paid" },
            { value: "pending" as const, label: "Pending" },
            { value: "failed" as const, label: "Failed" },
            { value: "refunded" as const, label: "Refunded" },
          ]}
        />
      </div>
      <p className="mt-3 text-xs text-fg-muted">GST (18%) is added on top: {formatINR(Math.round((Number.isFinite(f.amount) ? f.amount : 0) * 0.18))}.</p>
      <FormError error={act.error} />
    </Modal>
  );
}
